// Scanner — класс для чтения из стандартного ввода.
import java.util.Scanner;

public class SolutionCommented {
    public static void main(String[] args) {
        // Привязываем сканер к stdin. Для целых чисел Locale не нужен:
        // nextInt читает цифры одинаково на любой локали.
        Scanner sc = new Scanner(System.in);
        int n = sc.nextInt();
        // Целочисленное деление отбрасывает дробную часть:
        // 1234 / 1000 = 1 — это первая (старшая) цифра.
        int first = n / 1000;
        // Остаток от деления на 10 — последняя (младшая) цифра:
        // 1234 % 10 = 4.
        int last = n % 10;
        // Сначала отбрасываем старшую цифру (1234 % 1000 = 234),
        // потом отбрасываем младшую (234 / 10 = 23) — остаются две средние.
        int middle = (n % 1000) / 10;
        // Собираем число обратно: последняя цифра становится первой,
        // середина stays на месте, первая цифра становится последней.
        // Для 1234: 4 * 1000 + 23 * 10 + 1 = 4231.
        int result = last * 1000 + middle * 10 + first;
        // println печатает число и перенос строки. Ведущие нули у int
        // не сохраняются: 1000 -> 0001 -> печатается просто 1.
        System.out.println(result);
    }
}